-- Table: public.department
CREATE TABLE IF NOT EXISTS public.department (
    department_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    location TEXT,
    manager_id BIGINT
);

-- Table: public.employee
CREATE TABLE IF NOT EXISTS public.employee (
    employee_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auth_user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    department_id BIGINT REFERENCES public.department(department_id) ON DELETE SET NULL,
    manager_employee_id BIGINT REFERENCES public.employee(employee_id) ON DELETE SET NULL,
    first_name TEXT NOT NULL,
    last_name TEXT NOT NULL,
    gender TEXT CHECK (gender IN ('M', 'F')),
    email TEXT NOT NULL UNIQUE,
    hire_date DATE NOT NULL DEFAULT CURRENT_DATE,
    job_title TEXT,
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'on_leave', 'terminated')),
    role TEXT NOT NULL DEFAULT 'employee' CHECK (role IN ('admin', 'manager', 'employee')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Add Circular Foreign Key for department manager
ALTER TABLE public.department 
    DROP CONSTRAINT IF EXISTS fk_department_manager,
    ADD CONSTRAINT fk_department_manager 
    FOREIGN KEY (manager_id) REFERENCES public.employee(employee_id) ON DELETE SET NULL;

-- Table: public.project
CREATE TABLE IF NOT EXISTS public.project (
    project_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT REFERENCES public.department(department_id) ON DELETE SET NULL,
    manager_id BIGINT REFERENCES public.employee(employee_id) ON DELETE SET NULL,
    project_name TEXT NOT NULL,
    start_date DATE,
    end_date DATE,
    budget NUMERIC(12, 2),
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'completed', 'on_hold', 'cancelled'))
);

-- Table: public.assignment
CREATE TABLE IF NOT EXISTS public.assignment (
    employee_id BIGINT REFERENCES public.employee(employee_id) ON DELETE CASCADE,
    project_id BIGINT REFERENCES public.project(project_id) ON DELETE CASCADE,
    assigned_role TEXT,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (employee_id, project_id)
);

-- Table: public.attendance
CREATE TABLE IF NOT EXISTS public.attendance (
    attendance_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES public.employee(employee_id) ON DELETE CASCADE,
    attendance_date DATE NOT NULL,
    check_in TIME,
    check_out TIME,
    status TEXT NOT NULL CHECK (status IN ('present', 'absent', 'late', 'half_day')),
    hours_worked NUMERIC(4, 2)
);

-- Table: public.leaves
CREATE TABLE IF NOT EXISTS public.leaves (
    leave_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES public.employee(employee_id) ON DELETE CASCADE,
    leave_type TEXT NOT NULL CHECK (leave_type IN ('sick', 'casual', 'annual', 'unpaid')),
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    reason TEXT,
    approval_status TEXT NOT NULL DEFAULT 'pending' CHECK (approval_status IN ('pending', 'approved', 'rejected')),
    approved_by BIGINT REFERENCES public.employee(employee_id) ON DELETE SET NULL,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Table: public.payroll
CREATE TABLE IF NOT EXISTS public.payroll (
    payroll_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES public.employee(employee_id) ON DELETE CASCADE,
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    gross_pay NUMERIC(10, 2) NOT NULL,
    net_pay NUMERIC(10, 2) NOT NULL,
    pay_date DATE,
    payment_status TEXT NOT NULL DEFAULT 'pending' CHECK (payment_status IN ('pending', 'paid', 'failed'))
);

-- Table: public.audit_log
CREATE TABLE IF NOT EXISTS public.audit_log (
    audit_log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_employee_id BIGINT REFERENCES public.employee(employee_id) ON DELETE SET NULL,
    entity_type TEXT NOT NULL,
    entity_id BIGINT,
    action TEXT NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    old_values JSONB,
    new_values JSONB
);

-- Table: public.user_preferences
CREATE TABLE IF NOT EXISTS public.user_preferences (
    employee_id BIGINT PRIMARY KEY REFERENCES public.employee(employee_id) ON DELETE CASCADE,
    theme_mode TEXT NOT NULL DEFAULT 'light' CHECK (theme_mode IN ('light', 'dark')),
    accent_color TEXT NOT NULL DEFAULT 'blue' CHECK (accent_color IN ('red', 'blue', 'green', 'purple', 'orange', 'yellow'))
);

