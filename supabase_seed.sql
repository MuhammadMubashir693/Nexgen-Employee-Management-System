-- Helper macro to grant full access to authenticated & anon users for local development / testing
DO $$ 
DECLARE
    tbl text;
BEGIN
    FOR tbl IN 
        SELECT table_name 
        FROM information_schema.tables 
        WHERE table_schema = 'public' 
          AND table_name IN ('department', 'employee', 'project', 'assignment', 'attendance', 'leaves', 'payroll', 'audit_log', 'user_preferences')
    LOOP
        EXECUTE format('DROP POLICY IF EXISTS "Allow all authenticated users access to %I" ON public.%I;', tbl, tbl);
        EXECUTE format('CREATE POLICY "Allow all authenticated users access to %I" ON public.%I FOR ALL TO authenticated USING (true) WITH CHECK (true);', tbl, tbl);
        
        EXECUTE format('DROP POLICY IF EXISTS "Allow anon users access to %I" ON public.%I;', tbl, tbl);
        EXECUTE format('CREATE POLICY "Allow anon users access to %I" ON public.%I FOR ALL TO anon USING (true) WITH CHECK (true);', tbl, tbl);
    END LOOP;
END $$;

